const GLYPH_W = 5;
const GLYPH_H = 7;
const CHAR_SPACING = 1;

/**
 * Render a string at (x, y) using the pixel font.
 * scale = how many canvas pixels per logical pixel.
 */
export function renderText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  ctx.fillStyle = color;
  const upper = text.toUpperCase();
  let cursorX = x;

  for (const ch of upper) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    for (let col = 0; col < GLYPH_W; col++) {
      const column = glyph[col];
      for (let row = 0; row < GLYPH_H; row++) {
        if ((column >> row) & 1) {
          ctx.fillRect(
            Math.round(cursorX + col * scale),
            Math.round(y     + row * scale),
            scale,
            scale,
          );
        }
      }
    }
    cursorX += (GLYPH_W + CHAR_SPACING) * scale;
  }
}

/** Returns the pixel-width of a string at the given scale */
export function textWidth(text: string, scale = 1): number {
  return text.length * (GLYPH_W + CHAR_SPACING) * scale;
}

export const GLYPH_HEIGHT = GLYPH_H;
